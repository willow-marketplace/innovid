#!/usr/bin/env bash
# Copy shared/safety.md into every skill between its BEGIN/END markers.
# Each skill folder must stay self-contained (Agent Skills are installed one
# folder at a time), so the shared rules are copied in rather than linked.
#
# Usage:
#   scripts/sync-shared.sh          rewrite the blocks in place
#   scripts/sync-shared.sh --check  exit 1 if any skill is out of sync
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
src="$root/shared/safety.md"
begin='<!-- BEGIN shared/safety.md: generated by scripts/sync-shared.sh, edit the source file -->'
end='<!-- END shared/safety.md -->'
check=false
[[ "${1:-}" == "--check" ]] && check=true

status=0
for skill in "$root"/skills/*/SKILL.md; do
  if ! grep -qF "$begin" "$skill" || ! grep -qF "$end" "$skill"; then
    echo "missing shared block markers: ${skill#$root/}" >&2
    status=1
    continue
  fi
  tmp=$(mktemp)
  awk -v begin="$begin" -v end="$end" -v src="$src" '
    $0 == begin { print; while ((getline line < src) > 0) print line; close(src); skipping = 1; next }
    $0 == end   { skipping = 0 }
    !skipping   { print }
  ' "$skill" > "$tmp"
  if $check; then
    if ! cmp -s "$tmp" "$skill"; then
      echo "out of sync with shared/safety.md: ${skill#$root/}" >&2
      status=1
    fi
    rm -f "$tmp"
  else
    mv "$tmp" "$skill"
  fi
done
exit $status
